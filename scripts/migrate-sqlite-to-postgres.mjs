function buildCreateTableSql(name, def) {
  const cols = Object.entries(def.columns).map(([k, v]) => `${k} ${v}`);
  if (def.primaryKey) cols.push(def.primaryKey);
  return `CREATE TABLE IF NOT EXISTS ${name} (${cols.join(", ")})`;
}

// Tables migrated in order (all independent — no FKs).
const TABLE_ORDER = [
  "_meta",
  "settings",
  "providerConnections",
  "providerNodes",
  "proxyPools",
  "apiKeys",
  "combos",
  "kv",
  "usageHistory",
  "usageDaily",
  "requestDetails",
];

function parseArgs(argv) {
  const out = { truncate: false, sqlite: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--truncate") out.truncate = true;
    else if (argv[i] === "--sqlite") out.sqlite = argv[++i];
  }
  return out;
}

function defaultDataDir() {
  if (process.env.DATA_DIR) return process.env.DATA_DIR;
  if (process.platform === "win32") {
    return path.join(process.env.APPDATA || path.join(os.homedir(), "AppData", "Roaming"), "9router");
  }
  return path.join(os.homedir(), ".9router");
}

function resolveSqlitePath(arg) {
  if (arg) return path.resolve(arg);
  return path.join(defaultDataDir(), "db", "data.sqlite");
}

function openSqlite(sqlitePath) {
  let Database;
  try {
    Database = require("better-sqlite3");
  } catch {
    console.error("✖ better-sqlite3 is required to read the SQLite file.");
    console.error("  Install it first:  npm install better-sqlite3");
    process.exit(1);
  }
  if (!fs.existsSync(sqlitePath)) {
    console.error(`✖ SQLite file not found: ${sqlitePath}`);
    console.error("  Pass the correct path with --sqlite <path>.");
    process.exit(1);
  }
  return new Database(sqlitePath, { readonly: true, fileMustExist: true });
}

function makePool() {
  const connectionString = process.env.DATABASE_URL || undefined;
  if (!connectionString && !process.env.PGHOST && !process.env.PGUSER) {
    console.error("✖ DATABASE_URL is not set. Point it at your target PostgreSQL.");
    process.exit(1);
  }
  const sslRequested =
    process.env.DATABASE_SSL === "true" ||
    /[?&]sslmode=(require|verify-ca|verify-full)/.test(connectionString || "");
  const ssl = sslRequested
    ? { rejectUnauthorized: process.env.DATABASE_SSL_REJECT_UNAUTHORIZED === "true" }
    : undefined;
  return new pg.Pool({ connectionString, ssl, max: 4 });
}

async function ensureSchema(client) {
  for (const [name, def] of Object.entries(TABLES)) {
    await client.query(buildCreateTableSql(name, def));
    for (const idx of def.indexes || []) {
      try { await client.query(idx); } catch {}
    }
  }
}

function readTable(sdb, table) {
  try {
    return sdb.prepare(`SELECT * FROM ${table}`).all();
  } catch {
    return null; // table absent in old DB
  }
}

async function importTable(client, table, rows) {
  if (!rows || rows.length === 0) return 0;
  let inserted = 0;
  for (const row of rows) {
    const cols = Object.keys(row);
    if (cols.length === 0) continue;
    const colList = cols.join(", ");
    const placeholders = cols.map((_, i) => `$${i + 1}`).join(", ");
    const values = cols.map((c) => row[c]);
    const res = await client.query(
      `INSERT INTO ${table}(${colList}) VALUES(${placeholders}) ON CONFLICT DO NOTHING`,
      values
    );
    inserted += res.rowCount || 0;
  }
  return inserted;
}

async function resetIdentity(client) {
  // usageHistory.id is an IDENTITY column; advance its sequence past the
  // largest migrated id so future inserts don't collide.
  try {
    await client.query(
      `SELECT setval(pg_get_serial_sequence('usagehistory', 'id'),
                     GREATEST((SELECT COALESCE(MAX(id), 0) FROM usageHistory), 1))`
    );
  } catch (e) {
    console.warn(`  (could not reset usageHistory id sequence: ${e.message})`);
  }
}

async function main() {
  const { truncate, sqlite } = parseArgs(process.argv.slice(2));
  const sqlitePath = resolveSqlitePath(sqlite);

  console.log(`SQLite source : ${sqlitePath}`);
  const masked = (process.env.DATABASE_URL || "PG* env").replace(/:\/\/[^@]*@/, "://***@");
  console.log(`Postgres target: ${masked}`);

  const sdb = openSqlite(sqlitePath);
  const pool = makePool();
  const client = await pool.connect();

  try {
    console.log("\n→ Ensuring PostgreSQL schema...");
    await ensureSchema(client);

    if (truncate) {
      console.log("→ Truncating target tables (--truncate)...");
      for (const table of [...TABLE_ORDER].reverse()) {
        try { await client.query(`TRUNCATE TABLE ${table} RESTART IDENTITY`); } catch {}
      }
    }

    console.log("→ Copying rows...");
    await client.query("BEGIN");
    let total = 0;
    for (const table of TABLE_ORDER) {
      const rows = readTable(sdb, table);
      if (rows === null) {
        console.log(`  - ${table}: (absent in SQLite, skipped)`);
        continue;
      }
      const n = await importTable(client, table, rows);
      total += n;
      console.log(`  - ${table}: ${n}/${rows.length} inserted`);
    }
    await resetIdentity(client);
    await client.query("COMMIT");

    console.log(`\n✓ Done. ${total} rows imported into PostgreSQL.`);
  } catch (e) {
    try { await client.query("ROLLBACK"); } catch {}
    console.error("\n✖ Migration failed:", e.message);
    process.exitCode = 1;
  } finally {
    client.release();
    await pool.end();
    sdb.close();
  }
}

main();
